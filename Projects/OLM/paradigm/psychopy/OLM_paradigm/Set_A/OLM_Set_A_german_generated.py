# Matches 03_learning.sce lines 401-424:
#   order[] = {"learning-1","learning-2","learning-3","learning-4","control","control"}
#   shuffled so: first block not control AND no two adjacent identical types
#   the two control blocks get assigned "control-1"/"control-2" in shuffled order
def shuffle_block_order(orders):
    """Shuffle block order with the PCL's two constraints."""
    while True:
        random.shuffle(orders)
        ok = True
        if orders[0] == "control":
            ok = False
        for x in range(1, len(orders)):
            if orders[x-1] == orders[x]:
                ok = False
                break
        if ok: break
    return orders

