def run_learning_trial(img_path, phase="learning", block=1, rep=1,
                       trial_idx=1, all_pairs=None):
    """
    Phase 1 (TRIAL_DUR = 2.5 s):
        Map image shown; key labels visible in behavioural mode.
        Response collected any time during the window; window runs to end.
    Phase 2 (FEEDBACK_DUR = 2.0 s):
        Feedback text + correct-position (_k_) image.
    """
    meta  = parse_stim_name(img_path)
    fname = os.path.basename(img_path)

    # Phase 1 ────────────────────────────────────────────────────────────────
    main_img.setImage(img_path)
    main_img.draw()
    if not fmri_mode:
        key_label_left.draw()
        key_label_right.draw()
    win.flip()
    onset = global_clock.getTime()

    event.clearEvents()
    resp_clock = core.Clock()
    response = rt = None
    while resp_clock.getTime() < TRIAL_DUR:
        keys = event.getKeys(keyList=["left","right","escape"],
                             timeStamped=resp_clock)
        if keys:
            key, t = keys[0]
            if key == "escape":
                _csv_file.close(); win.close(); core.quit()
            response, rt = key, t
            break
        check_quit()

    # Wait out remainder of stimulus window
    elapsed = resp_clock.getTime()
    if elapsed < TRIAL_DUR:
        core.wait(TRIAL_DUR - elapsed)

    # Correctness: code 1 (left) on _k_ = correct; code 2 (right) on _i_ = correct
    is_k = "_k_" in fname
    resp_code = 1 if response == "left" else (2 if response == "right" else 0)
    if resp_code == 0:
        correct_flag = "timeout";   fb_label = "Zu spat!"
    elif (is_k and resp_code == 1) or (not is_k and resp_code == 2):
        correct_flag = "correct";   fb_label = "Richtig!"
    else:
        correct_flag = "incorrect"; fb_label = "Falsch!"

    # Find _k_ feedback image
    correct_fb = img_path
    if all_pairs:
        for pair in all_pairs:
            if pair["correct"] == img_path or img_path in pair["foils"]:
                correct_fb = pair["correct"]; break

    # Phase 2 ────────────────────────────────────────────────────────────────
    feed_text.text = f"{fb_label}   Die korrekte Position ist:"
    feed_img.setImage(correct_fb)
    feed_text.draw(); feed_img.draw()
    win.flip()
    core.wait(FEEDBACK_DUR)
    check_quit()

    write_row(Phase=phase, Block=block, Wdh=rep, Versuch=trial_idx,
              Stimulus=fname, StimTyp=meta["stim_type"],
              Richtung=meta["direction"], Seite=meta["side"],
              Antwort=response, Korrekt=correct_flag,
              RT=round(rt,4) if rt else "", Onset=round(onset,4))


